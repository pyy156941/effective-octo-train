template <typename T>
void exgcd(T a, T b, T &x, T &y)
{
	if (b == 0)
	{
		x = 1, y = 0;
		return;
	}
	exgcd(b, a % b, y, x);
	y -= a / b * x;
}

template <typename T>
T Inv(T a, T p)
{
	T x, y;
	exgcd(a, p, x, y);
	return (x + p) % p;
}

template <typename T>
T QPow(T a, T b, T mod)
{
	T ans = 1;
	while (b)
	{
		if (b & 1) ans = ans * a % mod;
		a = a * a % mod;
		b >>= 1;
	}
	return ans;
}

bool multiTest = true;

int a[100001];
void Solve()
{
	int n, ans = 0;
	cin >> n;
	for (int i = 1; i <= n; i++) cin >> a[i];
	if (n == 1) 
	{
		cout << a[1] << '\n';
		return;
	}
	else if (n == 2)
	{
		cout << min(a[1], a[2]) << '\n';
		return;
	}
	for (int i = 1; i <= n - 2; i++) 
	{
		int tmp[3];
		tmp[0] = a[i], tmp[1] = a[i + 1], tmp[2] = a[i + 2];
		sort(tmp, tmp + 3);
		ans = max(ans, tmp[1]);
	}
	cout << ans << '\n';
	return;
}

