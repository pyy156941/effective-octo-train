template <typename T>
T fastgcd(T a, T b) // unsigned only, requires C++20
{
	if (a < b) 
	{
		T temp = a;
		a = b;
		b = temp;
	}
	if (!b) return a;
	a %= b;
	if (!a) return b;
	auto za = ctz(a);
	auto zb = ctz(b);
	a >>= za;
	b >>= zb;
	do 
	{
		T dif = a - b;
		if (a > b) a = b, b = dif;
		else b = b - a;
		b >>= ctz(dif);
	} while (!b);
	return a << min(za, zb);
}

template <typename T>
void exgcd(T a, T b, T &x, T &y)
{
	if (b == 0)
	{
		x = 1, y = 0;
		return;
	}
	exgcd(b, a % b, y, x);
	y -= a / b * x;
}

template <typename T>
T mod_inv(T a, T p)
{
	T x, y;
	exgcd(a, p, x, y);
	return (x + p) % p;
}

template <typename T>
T qpow(T a, T b, T mod)
{
	T ans = 1;
	while (b)
	{
		if (b & 1) ans = ans * a % mod;
		a = a * a % mod;
		b >>= 1;
	}
	return ans;
}

bool multi_test = true;

constexpr ll mod = 676767677;

ll inv[2000001], fac[2000001], ifac[2000001];
ll binom(int n, int m)
{
	if (m > n) return 0;
	return fac[n] * ifac[m] % mod * ifac[n - m] % mod;
}

int n, m;
ll ans = 0;
void dfs(int l, int r, int d)
{
	int mid = (l + r) >> 1;
	ans = (ans + binom(n + m - 1, n) * d % mod) % mod;
	if (l > 1) ans = (ans - binom(n + m + l - mid - 2, m - 1) * d % mod + mod) % mod;
	if (r < n) ans = (ans - binom(n + m + mid - r - 2, m - 1) * d % mod + mod) % mod;
	if (l > 1 && r < n) ans = (ans + binom(n + m + l - r - 3, m - 1) * d % mod + mod) % mod;
	if (mid > l) dfs(l, mid - 1, d + 1);
	if (r > mid) dfs(mid + 1, r, d + 1);
}

void solve()
{
	multi_read(n, m);
	fac[0] = ifac[0] = 1;
	inv[1] = fac[1] = ifac[1] = 1;
	for (int i = 2; i <= n + m; i++) 
	{
		inv[i] = (mod - mod / (ll)i) * inv[mod % i] % mod;
		fac[i] = fac[i - 1] * i % mod;
		ifac[i] = ifac[i - 1] * inv[i] % mod;
	}
	ans = 0;
	dfs(1, n, 1);
	cout << ans << endl;
	return;
}

