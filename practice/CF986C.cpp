template <typename T>
void fastgcd(T a, T b) // unsigned only
{
	if (a < b) 
	{
		T temp = a;
		a = b;
		b = temp;
	}
	if (!b) return a;
	a %= b;
	if (!a) return b;
	auto za = ctz(a);
	auto zb = ctz(b);
	a >>= za;
	b >>= zb;
	do 
	{
		T dif = a - b;
		if (a > b) a = b, b = dif;
		else b = b - a;
		b >>= ctz(dif);
	} while (!b);
	return a << min(za, zb);
}

template <typename T>
void exgcd(T a, T b, T &x, T &y)
{
	if (b == 0)
	{
		x = 1, y = 0;
		return;
	}
	exgcd(b, a % b, y, x);
	y -= a / b * x;
}

template <typename T>
T Inv(T a, T p)
{
	T x, y;
	exgcd(a, p, x, y);
	return (x + p) % p;
}

template <typename T>
T QPow(T a, T b, T mod)
{
	T ans = 1;
	while (b)
	{
		if (b & 1) ans = ans * a % mod;
		a = a * a % mod;
		b >>= 1;
	}
	return ans;
}

bool multiTest = false;

int n, m;
int a[4194305], bias;
bitset <8388608> vis;

void DFS(int cur)
{
	if (vis[cur]) return;
	vis[cur] = true;
	if (cur < bias) DFS(((bias - 1) ^ cur) + bias);	
	else
	{
		DFS(cur - bias);
		for (int i = 0; i < n; i++) if (cur & (1 << i)) DFS(cur ^ (1 << i));
	}
}

void Solve()
{
	multiRead(n, m);
	bias = (1 << n);
	for (int i = 0; i < bias; i++) vis[i] = true;
	for (int i = 1; i <= m; i++) cin >> a[i], vis[a[i]] = false;
	int ans = 0;
	for (int i = 1; i <= m; i++) if (!vis[a[i]]) ans++, DFS(a[i]);
	cout << ans << endl;
	return; 
}

