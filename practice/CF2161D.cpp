template <typename T>
T fastgcd(T a, T b) // unsigned only, requires C++20
{
	if (a < b) 
	{
		T temp = a;
		a = b;
		b = temp;
	}
	if (!b) return a;
	a %= b;
	if (!a) return b;
	auto za = ctz(a);
	auto zb = ctz(b);
	a >>= za;
	b >>= zb;
	do 
	{
		T dif = a - b;
		if (a > b) a = b, b = dif;
		else b = b - a;
		b >>= ctz(dif);
	} while (!b);
	return a << min(za, zb);
}

template <typename T>
void exgcd(T a, T b, T &x, T &y)
{
	if (b == 0)
	{
		x = 1, y = 0;
		return;
	}
	exgcd(b, a % b, y, x);
	y -= a / b * x;
}

template <typename T>
T mod_inv(T a, T p)
{
	T x, y;
	exgcd(a, p, x, y);
	return (x + p) % p;
}

template <typename T>
T qpow(T a, T b, T mod)
{
	T ans = 1;
	while (b)
	{
		if (b & 1) ans = ans * a % mod;
		a = a * a % mod;
		b >>= 1;
	}
	return ans;
}

bool multi_test = true;

int n;
vector <ll> pt;
int dp[300001], pre_mx[300001];
ll to_id(int a, int p)
{
	return (ll)(a - 1) * n + n - p;
}

pair <int, int> to_pair(ll id)
{
	int a = id / (ll)n + 1;
	int p = n - id % (ll)n;
	return {a, p};
}

void solve()
{
	int v;
	cin >> n;
	pt.clear();
	for (int i = 1; i <= n; i++) cin >> v, pt.pb(to_id(v, i));
	sort(pt.begin(), pt.end());
	for (int i = 1; i <= n; i++) pre_mx[i] = 0;
	int cur_mx = 0, cur_a = 0;
	for (int i = 1; i <= n; i++)
	{
		auto [a, p] = to_pair(pt[i - 1]);
		if (a != cur_a) cur_a = a, cur_mx = 0;
		int pre = lower_bound(pt.begin(), pt.end(), to_id(a - 1, p)) - pt.begin();
		pre = max(pre, 0);
		pre = min(pre, i - 1);
		dp[i] = max(pre_mx[pre], cur_mx) + 1;
		// cerr << a << ' ' << p << ' ' << pre << ' ' << to_pair(pt[pre]).first << ' ' << to_pair(pt[pre]).second << ' ' << dp[i] << endl;
		pre_mx[i] = max(pre_mx[i - 1], dp[i]);
		cur_mx = max(cur_mx, dp[i]);
	}
	cout << n - pre_mx[n] << endl;
	return;
}

int main()
{
	ios :: sync_with_stdio(false);
	cin.tie(nullptr);
	int _ = 1;
	if (multi_test) cin >> _;
	while (_--) solve();
	return 0;
}